    public static GlossaryEntry? Find(string key) => Entries.FirstOrDefault(e => e.Key == key);

    public static IReadOnlyList<GlossaryEntry> Search(string? text) =>
        string.IsNullOrWhiteSpace(text)
            ? Entries
            : Entries.Where(e => e.Term.Contains(text, StringComparison.OrdinalIgnoreCase)
                || e.Short.Contains(text, StringComparison.OrdinalIgnoreCase)
                || e.Long.Contains(text, StringComparison.OrdinalIgnoreCase)).ToList();

    public static string? KeyForSignal(string signalName) => signalName switch
    {
        "vwap" => "vwap",
        "opening-range" => "opening-range",
        "relative-volume" => "rvol",
        "intraday-momentum" or "momentum" => "momentum",
        "previous-day" => "rompimento",
        "gap" => "gap",
        "catalyst" => "catalisador",
        "recent-news" or "sentiment" => "sentimento",
        "trend" => "ema",
        "bollinger" => "bollinger",
        _ => null
    };
